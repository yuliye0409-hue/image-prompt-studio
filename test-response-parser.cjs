const fs = require("node:fs");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const source = fs.readFileSync("src/background.js", "utf8");
const context = {};
vm.createContext(context);
const start = source.indexOf("function extractOpenAIText(");
const end = source.indexOf("function getCompatibleApiMessage(", start);
vm.runInContext(source.slice(start, end) + "\nfunction parseJson(text){try{return JSON.parse(text)}catch{return null}}", context);
const extract = context.extractOpenAIText;
const answer = "中文 Prompt：黑色产品。\nEnglish Prompt: Black product.";
const payload = {input:[{role:"system",content:"Skill naming: private instructions"}],instructions:"ignore this",usage:{output_tokens_details:{text:"bad"}},output:[{type:"reasoning",summary:[{text:"not final"}]},{type:"message",role:"assistant",content:[{type:"output_text",text:answer}]}]};
assert.equal(extract(payload),answer);
assert.equal(extract({output:[{type:"message",role:"user",content:[{type:"input_text",text:"do not return"}]}],metadata:{text:"secret"},usage:{text:"wrong"}}),"");
assert.equal(extract({choices:[{message:{role:"assistant",content:answer}}]}),answer);
assert.equal(extract(JSON.stringify(payload)),answer);
assert.equal(extract({output_text:answer,output:payload.output}),answer);
assert.equal(extract({response:payload}),answer);
const stream = ["event: response.output_text.delta","data: "+JSON.stringify({type:"response.output_text.delta",delta:"中文 Prompt：黑色产品。\n"}),"","data: "+JSON.stringify({type:"response.output_text.delta",delta:"English Prompt: Black product."}),"data: "+JSON.stringify({type:"response.completed",response:payload}),"data: [DONE]"].join("\n");
assert.equal(context.parseCompatibleResponse(stream),answer);
assert.equal(context.parseCompatibleResponse("data: "+JSON.stringify({type:"response.output_text.delta",delta:"Hello "})+"\ndata: "+JSON.stringify({type:"response.output_text.delta",delta:"world"})),"Hello world");
assert.equal(context.parseCompatibleResponse("data: {invalid JSON}\ndata: [DONE]"),"");
assert.equal(context.isCleanPromptResult(answer),true);
assert.equal(context.isCleanPromptResult("Skill naming: If a plugin contributes skills"),false);
assert.equal(context.isCleanPromptResult('{"usage":{"output_tokens":123}}'),false);
console.log("Strict final-message extraction, metadata isolation, wrappers, SSE and invalid-result checks passed.");
